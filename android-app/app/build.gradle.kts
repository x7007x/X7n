        storeFile = keyFile
        storePassword = System.getenv("STORE_PASSWORD") ?: debugStorePassword
        keyAlias = System.getenv("KEY_ALIAS") ?: debugKeyAlias
        keyPassword = System.getenv("KEY_PASSWORD") ?: debugKeyPassword
