// ---------------------------------------------------------------------------
// Debug keystore: generated automatically at build time with keytool.
// No binary keystore files are stored in the repository; the generation
// command and alias live as plain text inside this file, while the random
// UUID passwords are persisted (gitignored) in debug.keystore.properties so
// subsequent builds can still open the same keystore.
// ---------------------------------------------------------------------------
val debugKeyAlias = "EgyptologyDebugKey"

val debugKeystoreFile = rootProject.file("debug.keystore")
val debugKeystoreProps = rootProject.file("debug.keystore.properties")

// Reuse the stored secret when a keystore was generated by a previous build.
private fun loadStoredSecret(): String? {
  if (!debugKeystoreFile.exists() || !debugKeystoreProps.exists()) return null
  return runCatching {
    Properties().apply { debugKeystoreProps.inputStream().use { load(it) } }
      .getProperty("storePassword")
      ?.takeIf { it.isNotBlank() }
  }.getOrNull()
}

// PKCS12 keystores (the JDK default) require the key password to match the
// store password, so one random UUID secures both.
val debugStorePassword = loadStoredSecret() ?: UUID.randomUUID().toString()
val debugKeyPassword = debugStorePassword

// Generates the keystore on first build only. A dedicated task class with
// injected properties keeps it compatible with the configuration cache.
abstract class GenerateDebugKeystoreTask : DefaultTask() {
  @get:Internal abstract val keystoreFile: RegularFileProperty
  @get:Internal abstract val propsFile: RegularFileProperty
  @get:Internal abstract val keyAlias: Property<String>
  @get:Internal abstract val storePassword: Property<String>
  @get:Internal abstract val keyPassword: Property<String>

  @TaskAction
  fun generate() {
    propsFile.get().asFile.writeText(
      """
      |# Auto-generated by app/build.gradle.kts - do not commit.
      |storePassword=${storePassword.get()}
      |keyPassword=${keyPassword.get()}
      |alias=${keyAlias.get()}
      """.trimMargin()
    )
    val keytool = File(System.getProperty("java.home"), "bin/keytool").absolutePath
    val process = ProcessBuilder(
      keytool, "-genkeypair",
      "-keystore", keystoreFile.get().asFile.absolutePath,
      "-storepass", storePassword.get(),
      "-keypass", keyPassword.get(),
      "-alias", keyAlias.get(),
      "-keyalg", "RSA",
      "-keysize", "2048",
      "-validity", "10000",
      "-dname", "CN=Android Debug,O=Android,C=US"
    ).redirectErrorStream(true).start()
    val output = process.inputStream.bufferedReader().readText()
    if (process.waitFor() == 0) {
      println("Generated debug.keystore.")
    } else {
      throw GradleException("Failed to generate debug.keystore: $output")
    }
  }
}

val generateDebugKeystore = tasks.register<GenerateDebugKeystoreTask>("generateDebugKeystore") {
  group = "build"
  description = "Generates debug.keystore with keytool if it does not exist."
  keystoreFile.set(debugKeystoreFile)
  propsFile.set(debugKeystoreProps)
  keyAlias.set(debugKeyAlias)
  storePassword.set(debugStorePassword)
  keyPassword.set(debugKeyPassword)
  onlyIf {
    !keystoreFile.get().asFile.exists() || !propsFile.get().asFile.exists()
  }
}

// Signing happens in packaging/validation tasks - make sure they run after generation.
tasks.matching {
  it.name.startsWith("package") || it.name.startsWith("validateSigning")
}.configureEach {
  dependsOn(generateDebugKeystore)
}

